#!/usr/bin/env python3
"""Project-archetype generator: builds career/05-portfolio/project-archetypes.md from the archetype data.

Each of the proof-of-work archetypes gets one card: the problem it solves, how to build it, the evidence to
publish (mapped to the T0-13 artefacts PA-01–PA-15), its verifiability target on the T0-13 ladder (V0–V3),
effort and compute, the system-design interview archetypes it prepares for (T0-14 A1–A15), the
anti-portfolio pitfalls it must avoid (T0-13 AP-1–AP-9), and the skills it evidences.

Inputs (sources of truth):
  * data/project_archetypes.json (+ data/schemas/project_archetypes.schema.json)   the cards
  * data/skills_ontology.json        skill names, verifiability ladder, role skill tiers
  * data/stack_model.json            where each archetype sits on the role map
  * data/interview_prompts.json      names of the system-design archetypes (optional)
  * scripts/resume_layers.py         which roles each archetype covers, and the minimal sets (Grade M)

Usage:
    python3 scripts/build_archetypes.py            # print the page
    python3 scripts/build_archetypes.py --update   # write career/05-portfolio/project-archetypes.md
    python3 scripts/build_archetypes.py --check    # exit 1 if it is out of date or the data are invalid

Standard library only.
"""
import argparse
import json
import sys
from pathlib import Path

sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parent))
import stack_lib as sl  # noqa: E402
from build_resume_matrix import project  # noqa: E402
from build_role_map import archetype_places  # noqa: E402
from build_skills import load_ontology, schema_errors  # noqa: E402
from resume_layers import THRESHOLD, analyse  # noqa: E402

ROOT = sl.ROOT
DOC = ROOT / "career" / "05-portfolio" / "project-archetypes.md"
SCHEMA = ROOT / "data" / "schemas" / "project_archetypes.schema.json"
PROMPTS = ROOT / "data" / "interview_prompts.json"
BEST_FOR_MIN = 0.25   # show a role under "best for" when one project covers at least this share of its weighted Must + Important skills
EFFORT = {"S": "small", "M": "medium", "L": "large"}


def esc(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def skill_name(onto, sid):
    e = onto["skills"].get(sid) or onto["classes"].get(sid)
    return e["name"] if e else sid


def validate(data, onto):
    errs = []
    if SCHEMA.exists():
        schema = json.loads(SCHEMA.read_text(encoding="utf-8"))
        errs += [f"project_archetypes.json {e[2:]}" for e in schema_errors(data, schema, schema)]
    known = set(onto["skills"]) | set(onto["classes"])
    for pid, p in data["archetypes"].items():
        errs += [f"project_archetypes.json: {pid} names unknown skill {s}" for s in p["skills"] if s not in known]
        for f in ("problem", "build", "evidence", "verifiability", "effort", "compute", "interview_archetypes", "pitfalls", "sources"):
            if f not in p:
                errs.append(f"project_archetypes.json: {pid} has no '{f}'")
        for a in p.get("interview_archetypes", []):
            if not (a.startswith("A") and a[1:].isdigit() and 1 <= int(a[1:]) <= 15):
                errs.append(f"project_archetypes.json: {pid} interview archetype {a!r} is not A1-A15")
    return errs


def render(data, onto, stack, prompts):
    arch = data["archetypes"]
    an = analyse(project(onto), arch)
    R, ic = an["R"], an["ic"]
    places = {pid: code for code, items in archetype_places(stack, onto, arch).items() for pid, _ in items}
    ladder = onto["meta"]["verifiability"]
    a_names = {k: v["name"] for k, v in (prompts or {}).get("archetypes", {}).items()}
    hub = lambda rid: f"[{R[rid]['name'].split(' (')[0]}](../02-roles/hubs/{rid}.md)"  # noqa: E731

    def best_for(pid):
        covs = sorted(((an["role_cov"](rid, [pid]), -R[rid]["target"], rid) for rid in ic), reverse=True)
        return [(c, rid) for c, _, rid in covs if c >= BEST_FOR_MIN][:3]

    def ia(a):
        return f"{a} {a_names[a]}" if a in a_names else a

    n = len(arch)
    out = ["---", "id: portfolio.project-archetypes", 'title: "Project Archetypes: Proof-of-Work Projects, Specified"',
           "content_type: reference", "stage: 5", "status: published", f"last_verified: {data['as_of']}",
           *([f"review_by: {data['review_by']}"] if data.get("review_by") else []),
           f'summary: "The {n} proof-of-work project archetypes as build cards: the problem, the steps, the evidence to publish, the '
           'verifiability target, effort, the interviews each prepares for, pitfalls, and the roles it covers."',
           "sources: [T0-13, T0-14, T0-05, T0-06]", "tags: [portfolio, projects, proof-of-work]",
           "generated_by: scripts/build_archetypes.py", "---", "",
           "<!-- Generated by scripts/build_archetypes.py from data/project_archetypes.json. Edit the data, not this page. -->", "",
           "# Project Archetypes: Proof-of-Work Projects, Specified", "",
           f"> {n} projects that prove you can do GenAI work, each specified as a build card: what problem it solves, how to build it, "
           "what evidence to publish, how verifiable it must be, and which roles and interviews it prepares you for.", "",
           "## How to use this page", "",
           "1. **Pick by target role.** \"Best for\" lists the roles whose Must and Important skills one project covers most "
           f"(at least {BEST_FOR_MIN:.0%} of their weighted skills; computed, Grade M). Your role's hub lists its top projects too.",
           "2. **Build to the verifiability target.** V1 means reproducible, V2 externally attested, V3 operationally evidenced "
           "([proof-of-work standards](proof-of-work-standards.md), T0-13 §4.1). Headline claims need at least V1.",
           "3. **Publish the evidence, not the demo.** Each card lists the artefacts to publish, keyed to T0-13's PA-01–PA-15.",
           "4. **Avoid the anti-portfolio.** Each card names the AP-1–AP-9 traps it is prone to.",
           "5. **Use fewer projects, better.** Two or three deep projects beat many shallow ones; the minimal sets below cover the most roles.", "",
           "## At a glance", "",
           "| ID | Archetype | Where on the map | Best for | Verifiability | Effort | Interview archetypes |",
           "|---|---|---|---|:---:|:---:|---|"]
    for pid, p in arch.items():
        bf = ", ".join(f"{hub(rid)} {c:.0%}" for c, rid in best_for(pid)) or "—"
        where = sl.area_label(stack, places[pid]) if pid in places else "— (its skills are mostly cross-cutting)"
        out.append(f"| [{pid}](#{pid.lower()}) | {esc(p['name'])} | {where} | {bf} | {p['verifiability']} | "
                   f"{p['effort']}{' · ' + p['spec'] if p.get('spec') else ''} | {', '.join(p['interview_archetypes']) or '—'} |")
    all_ok = sum(an["role_cov"](k, an["all_set"]) >= THRESHOLD - 1e-9 for k in ic)
    top_ok = sum(an["role_cov"](k, an["top8_set"]) >= THRESHOLD - 1e-9 for k in an["top8"])

    def set_text(ids):
        return ", ".join(f"{p} {arch[p]['name']}" for p in ids)
    out += ["", "Coverage percentages are model outputs (Grade M) from judgement-graded skill tiers and archetype skill lists. "
            "\"Where on the map\" places each project where most of its skills sit on the [role map](../02-roles/role-map.md).", "",
            "## Minimal project sets", "",
            f"The smallest sets of archetypes that bring roles to at least {THRESHOLD:.0%} coverage of their weighted Must and Important "
            "skills (greedy search, Grade M; [job-search strategy §2.6](../06-job-search/job-search-strategy.md#26-the-constraints-that-bind-first)):", "",
            "| Goal | Set | Roles reaching the threshold |", "|---|---|:---:|",
            f"| Every individual-contributor role | {set_text(an['all_set'])} | {all_ok} of {len(ic)} |",
            f"| The top 8 GenAI targets | {set_text(an['top8_set'])} | {top_ok} of {len(an['top8'])} |",
            "", "Nobody needs every role. Choose your targets first ([targeting workbook](../00-start/targeting-workbook.md)), then the "
            "two or three archetypes that cover them best.", "",
            "## The cards", ""]
    for pid, p in arch.items():
        bf = best_for(pid)
        out += [f"<a id=\"{pid.lower()}\"></a>", "", f"### {pid} · {p['name']}", "",
                f"**The problem.** {p['problem']}", ""]
        if bf:
            out += ["**Best for:** " + ", ".join(f"{hub(rid)} ({c:.0%})" for c, rid in bf) + "."
                    + (f" **On the map:** {sl.area_label(stack, places[pid])}." if pid in places else ""), ""]
        out += ["**Build it:**", ""] + [f"{i}. {s}" for i, s in enumerate(p["build"], 1)] + [""]
        out += ["**Evidence to publish:**", ""] + [f"- {e}" for e in p["evidence"]] + [""]
        v = p["verifiability"]
        out += [f"**Verifiability target:** {v}: {ladder.get(v, '')}.", "",
                f"**Effort and compute:** {EFFORT.get(p['effort'], p['effort'])}"
                + (f" (reference spec {p['spec']}, T0-13 D3)" if p.get("spec") else " [P]") + f". {p['compute']}", ""]
        if p["interview_archetypes"]:
            out += ["**Prepares you for:** " + ", ".join(ia(a) for a in p["interview_archetypes"])
                    + " in [system-design archetypes](../08-interviewing/system-design-archetypes.md).", ""]
        out += ["**Avoid:** " + "; ".join(p["pitfalls"]) + ".", "",
                "**Skills it evidences:** " + ", ".join(skill_name(onto, s) for s in p["skills"]) + ".", "",
                "**Sources:** " + ", ".join(p["sources"]) + ".", ""]
    out += ["## Evidence and limits", "",
            f"- {data['basis']}",
            "- \"Best for\" percentages and the minimal sets are computed (Grade M) from the archetypes' skill lists and the roles' "
            "headline Must and Important skills; they rank options, they do not predict offers.",
            "- Effort labels without a reference spec are practice-curated [P]. No session measures how long these projects take.",
            "- What makes a project credible is its evidence: the verifiability level and the artefacts, not the topic "
            "([proof-of-work standards](proof-of-work-standards.md)).", "",
            "## Next steps", "",
            "- [Proof-of-work standards](proof-of-work-standards.md): the verifiability ladder, the artefacts, the anti-portfolio and how many projects.",
            "- [Online presence](../07-networking/online-presence.md): where to publish the evidence.",
            "- [System-design archetypes](../08-interviewing/system-design-archetypes.md): the interviews these projects prepare you for.",
            "- [Role hubs](../02-roles/hubs/README.md): the projects that cover each role.", ""]
    return "\n".join(out)


def build():
    data = json.loads(sl.ARCHETYPES.read_text(encoding="utf-8"))
    onto, stack = load_ontology(), sl.load(sl.STACK)
    errs = validate(data, onto)
    if errs:
        raise SystemExit("project archetypes are invalid:\n  " + "\n  ".join(errs[:30]))
    prompts = json.loads(PROMPTS.read_text(encoding="utf-8")) if PROMPTS.exists() else None
    return render(data, onto, stack, prompts)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--update", action="store_true")
    g.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = build()
    if args.update:
        DOC.write_text(text, encoding="utf-8")
        print(f"wrote {DOC.relative_to(ROOT)}")
    elif args.check:
        if not DOC.exists() or DOC.read_text(encoding="utf-8") != text:
            print(f"out of date: {DOC.relative_to(ROOT)}")
            sys.exit(1)
        print("up to date")
    else:
        print(text)


if __name__ == "__main__":
    main()
