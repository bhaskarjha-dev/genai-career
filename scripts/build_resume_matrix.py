#!/usr/bin/env python3
"""Resume skills matrix generator for the GenAI career catalogs.

Reads data/skills_ontology.json (the typed skills ontology) and generates
every computed block in career/06-job-search/resume-skills-matrix.md. The matrix is the concise
resume layer: it shows only the headline skills (ontology entries flagged
"headline", including the choose-one classes such as "AWS / Azure / GCP"); the
complete typed inventory per role is generated by scripts/build_skills.py.
Blocks:

  * the shared-skill layer across engineering roles
  * a skills-section blueprint for each resume variant (anchor role + sibling swap-ins)
  * the role-by-role matrix (must / important / should / optional, avoid,
    prerequisites, proof of work, posting terms to mirror)

Usage:
    python3 scripts/build_resume_matrix.py              # print all generated blocks
    python3 scripts/build_resume_matrix.py --update     # rewrite the GENERATED blocks in the matrix doc
    python3 scripts/build_resume_matrix.py --check      # exit 1 if the doc is out of date

Standard library only.
"""
import argparse
import json
import re
import sys
from collections import OrderedDict
from pathlib import Path

sys.dont_write_bytecode = True  # keep scripts/ free of __pycache__ when importing the shared validator
sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_skills import validate_ontology  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_DATA = ROOT / "data" / "skills_ontology.json"
DEFAULT_DOC = ROOT / "career" / "06-job-search" / "resume-skills-matrix.md"
TIERS = ["must", "important", "should", "optional"]
ENGINEERING_VARIANTS = {"A", "B", "C", "D"}
SHARED_ROWS = 14
MARKER_LABEL = OrderedDict([("shared", "shared layer"), ("blueprints", "variant blueprints"), ("roles", "role blocks")])
END_MARKER = "\n<!-- END GENERATED -->"
SLUG = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")


# ---------------------------------------------------------------- ontology projection
TIER_CODE = OrderedDict([("must", "M"), ("important", "I"), ("should", "S"), ("optional", "O")])


def project(onto):
    """Project the ontology onto the concise resume layer: headline skills and classes only,
    tier lists in link order, plus the role texts and resume variants."""
    headline = OrderedDict()
    for table in ("skills", "classes"):
        for k, v in onto[table].items():
            if v.get("headline"):
                headline[k] = OrderedDict([("name", v["name"]), ("group", v.get("group", ""))])
    roles = OrderedDict()
    for rid, r in onto["roles"].items():
        nr = OrderedDict((k, r[k]) for k in ("name", "target", "variant", "flavour", "basis") if k in r)
        if "covers" in r:
            nr["covers"] = r["covers"]
        for tier, code in TIER_CODE.items():
            nr[tier] = [l["id"] for l in r["links"] if l["tier"] == code and l["id"] in headline]
        for k in ("avoid", "prereq", "proof", "mirror"):
            nr[k] = r.get(k, "")
        roles[rid] = nr
    return OrderedDict([("skills", headline), ("variants", onto["resume_variants"]), ("roles", roles)])


# ---------------------------------------------------------------- validation
def validate(data):
    errors = []
    skills, roles, variants = data["skills"], data["roles"], data["variants"]
    flavours = {f for v in variants.values() for f in v["flavours"]}
    targets = []
    for rid, r in roles.items():
        if not SLUG.match(rid):
            errors.append(f"{rid}: bad slug")
        seen = []
        for t in TIERS:
            for k in r[t]:
                if k not in skills:
                    errors.append(f"{rid}: unknown skill '{k}' in {t}")
                seen.append(k)
        dup = sorted({k for k in seen if seen.count(k) > 1})
        if dup:
            errors.append(f"{rid}: skills listed in more than one tier: {dup}")
        if not r["must"] or not r["important"]:
            errors.append(f"{rid}: must and important tiers may not be empty")
        if r["flavour"] not in flavours or r["variant"] not in variants or not r["flavour"].startswith(r["variant"]):
            errors.append(f"{rid}: inconsistent variant/flavour {r['variant']}/{r['flavour']}")
        if isinstance(r["target"], int):
            targets.append(r["target"])
        for f in ("name", "basis", "avoid", "prereq", "proof", "mirror"):
            if not str(r.get(f, "")).strip():
                errors.append(f"{rid}: missing {f}")
    if sorted(targets) != list(range(1, len(targets) + 1)):
        errors.append(f"IC target ranks must be 1..{len(targets)} without gaps: {sorted(targets)}")
    if errors:
        raise SystemExit("skills_ontology.json (concise resume projection) is invalid:\n  " + "\n  ".join(errors))


# ---------------------------------------------------------------- helpers
def tkey(r):
    return r["target"] if isinstance(r["target"], int) else 1000


def names(data, ids):
    return ", ".join(data["skills"][k]["name"] for k in ids) if ids else "—"


def short(name):
    return name.split(" (")[0]


def tag(r):
    return f"#{r['target']}" if isinstance(r["target"], int) else r["target"]


# ---------------------------------------------------------------- blocks
def shared_block(data):
    roles = [r for r in data["roles"].values() if r["variant"] in ENGINEERING_VARIANTS]
    n = len(roles)
    mi, anyt = {}, {}
    for r in roles:
        for k in r["must"] + r["important"]:
            mi[k] = mi.get(k, 0) + 1
        for k in r["must"] + r["important"] + r["should"]:
            anyt[k] = anyt.get(k, 0) + 1
    out = [f"| Skill | Must or Important in (of {n} engineering roles) | Listed at any tier from Must to Should |",
           "|---|:---:|:---:|"]
    for k in sorted(anyt, key=lambda k: (-mi.get(k, 0), -anyt[k], data["skills"][k]["name"]))[:SHARED_ROWS]:
        out.append(f"| {data['skills'][k]['name']} | {mi.get(k, 0)} ({100 * mi.get(k, 0) / n:.0f}%) | "
                   f"{anyt[k]} ({100 * anyt[k] / n:.0f}%) |")
    return "\n".join(out)


def blueprints(data):
    by_flavour = OrderedDict()
    for rid, r in data["roles"].items():
        by_flavour.setdefault(r["flavour"], []).append(rid)
    rows = []
    for vid, v in data["variants"].items():
        for fid, fdesc in v["flavours"].items():
            rids = sorted(by_flavour.get(fid, []), key=lambda x: tkey(data["roles"][x]))
            if not rids:
                continue
            anchor = data["roles"][rids[0]]
            base = anchor["must"] + anchor["important"]
            swaps = [(x, [k for k in data["roles"][x]["must"] + data["roles"][x]["important"] if k not in base])
                     for x in rids[1:]]
            should = {}
            for x in rids:
                for k in data["roles"][x]["should"]:
                    should[k] = should.get(k, 0) + 1
            hyg = [k for k in sorted(should, key=lambda k: -should[k])
                   if k not in base and should[k] / len(rids) >= 0.5 - 1e-9]
            rows.append((fid, fdesc.split(":")[0], rids[0], base, swaps, hyg))
    return rows


def blueprint_block(data):
    out = ["| Variant | Anchor role (base skills section = its Must + Important skills) | "
           "Swap in for sibling roles (their Must/Important skills the anchor lacks) | Hygiene: list if true |",
           "|---|---|---|---|"]
    for fid, label, anchor_id, base, swaps, hyg in blueprints(data):
        a = data["roles"][anchor_id]
        sw = "; ".join(f"**[{short(data['roles'][x]['name'])}](#resume-{x}):** {names(data, e)}" for x, e in swaps) or "—"
        out.append(f"| **{fid}** {label} | **[{a['name']}](#resume-{anchor_id}):** {names(data, base)} | {sw} | {names(data, hyg)} |")
    return "\n".join(out)


def role_links(rid, r):
    profiles = r.get("covers", [rid])
    if len(profiles) == 1:
        prof = f"[Role profile](../02-roles/role-catalog.md#profile-{rid})"
    else:
        prof = " · ".join(f"[Role profile: {p}](../02-roles/role-catalog.md#profile-{p})" for p in profiles)
    skills_anchor = "skills-leadership" if r["variant"] == "L" else f"skills-{rid}"
    return (f"{prof} · [Full skill map](../03-skills-and-tech/role-skill-maps.md#{skills_anchor}) · "
            f"[Complete typed inventory](../03-skills-and-tech/inventories/{rid}.md)")


def roles_block(data):
    out = []
    for rid, r in sorted(data["roles"].items(), key=lambda kv: tkey(kv[1])):
        out += [f'<a id="resume-{rid}"></a>',
                f"#### {tag(r)} · {r['name']} · variant {r['flavour']}",
                f"*Basis: {r['basis']}.*", "",
                "| Tier | Skills, in priority order |", "|---|---|",
                f"| **Must** | {names(data, r['must'])} |",
                f"| **Important** | {names(data, r['important'])} |",
                f"| **Should** | {names(data, r['should'])} |",
                f"| **Optional** | {names(data, r['optional'])} |",
                f"| **Avoid** | {r['avoid']} |", "",
                f"- **Prerequisites:** {r['prereq']}.",
                f"- **Proof to show:** {r['proof']}.",
                f"- **Posting terms to mirror:** {r['mirror']}.",
                f"- **Links:** {role_links(rid, r)}", ""]
    return "\n".join(out).rstrip("\n")


def build(data):
    return OrderedDict([("shared", shared_block(data)), ("blueprints", blueprint_block(data)), ("roles", roles_block(data))])


# ---------------------------------------------------------------- doc update
def doc_blocks(text):
    found = {}
    for key, label in MARKER_LABEL.items():
        begin = f"<!-- BEGIN GENERATED: scripts/build_resume_matrix.py ({label}) -->\n"
        if text.count(begin) != 1:
            raise SystemExit(f"expected exactly one marker {begin.strip()!r}")
        i = text.index(begin) + len(begin)
        # Search from the newline that ends the BEGIN line, so an empty block is found too.
        j = text.find(END_MARKER, i - 1)
        if j < 0 or "<!-- BEGIN GENERATED" in text[i:j]:
            raise SystemExit(f"no END marker after {begin.strip()!r}")
        found[key] = (i, j)  # j == i - 1 for an empty block; text[i:j] is then ''
    return found


def update_doc(path, blocks):
    path = Path(path)
    text = path.read_text(encoding="utf-8")
    for key in reversed(list(MARKER_LABEL)):
        i, j = doc_blocks(text)[key]
        text = text[:i] + blocks[key] + text[j:]
    path.write_text(text, encoding="utf-8")


def check_doc(path, blocks):
    text = Path(path).read_text(encoding="utf-8")
    stale = [MARKER_LABEL[k] for k, (i, j) in doc_blocks(text).items() if text[i:j] != blocks[k]]
    return stale


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--data", default=str(DEFAULT_DATA))
    ap.add_argument("--update", nargs="?", const=str(DEFAULT_DOC), metavar="DOC",
                    help="rewrite the GENERATED blocks of the matrix doc in place (default: %(const)s)")
    ap.add_argument("--check", nargs="?", const=str(DEFAULT_DOC), metavar="DOC",
                    help="exit 1 if the GENERATED blocks of the matrix doc are out of date")
    args = ap.parse_args()
    onto = json.loads(Path(args.data).read_text(encoding="utf-8"), object_pairs_hook=OrderedDict)
    problems = validate_ontology(onto)
    if problems:
        raise SystemExit("skills_ontology.json is invalid (run scripts/build_skills.py for details):\n  " + "\n  ".join(problems[:50]))
    data = project(onto)
    validate(data)
    blocks = build(data)
    if args.check:
        stale = check_doc(args.check, blocks)
        if stale:
            print("out of date: " + ", ".join(stale))
            sys.exit(1)
        print("up to date")
    elif args.update:
        update_doc(args.update, blocks)
        print(f"updated {len(blocks)} generated blocks in {args.update}")
    else:
        for key, label in MARKER_LABEL.items():
            print(f"### {label}\n\n{blocks[key]}\n")


if __name__ == "__main__":
    main()
