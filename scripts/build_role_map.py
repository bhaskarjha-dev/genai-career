#!/usr/bin/env python3
"""Role-map generator: builds career/02-roles/role-map.md from the stack model and the role data.

Inputs (sources of truth):
  * data/stack_model.json   layers, planes, category map, specialisations (decision D-015)
  * data/role_scores.json   each role's family, work footprint (stack), definition and interview track
  * data/skills_ontology.json  skill names and categories
  * data/project_archetypes.json  proof-of-work archetypes, placed on the map by their skills' categories

The map shows where each role's work sits. It is not a pay or demand model: pay tracks employer tier and
seniority, not layer [B · T0-03 KF1].

Usage:
    python3 scripts/build_role_map.py            # print the document
    python3 scripts/build_role_map.py --update   # write career/02-roles/role-map.md
    python3 scripts/build_role_map.py --check    # exit 1 if it is out of date or the data are inconsistent

Standard library only.
"""
import argparse
import sys
from collections import Counter, OrderedDict
from pathlib import Path

sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parent))
import stack_lib as sl  # noqa: E402

DOC = sl.ROOT / "career" / "02-roles" / "role-map.md"


def skill_category(onto, sid):
    if sid in onto["skills"]:
        return onto["skills"][sid]["category"]
    members = onto["classes"].get(sid, {}).get("members", [])
    cats = Counter(onto["skills"][m]["category"] for m in members if m in onto["skills"])
    return cats.most_common(1)[0][0] if cats else None


def skill_name(onto, sid):
    e = onto["skills"].get(sid) or onto["classes"].get(sid)
    return e["name"] if e else sid


def archetype_places(stack, onto, archetypes):
    """Place each archetype where most of its skills' categories sit (layers and planes only)."""
    cmap, order = sl.category_area(stack), list(sl.areas(stack))
    out = OrderedDict((a, []) for a in order)
    for pid, p in archetypes.items():
        counts = Counter(cmap.get(skill_category(onto, s)) for s in p["skills"])
        counts.pop(None, None)
        if not counts:
            continue
        top = max(counts.values())
        best = next(a for a in order if counts.get(a) == top)
        out[best].append((pid, p["name"]))
    return out


def link(r):
    return f"[{r['name']}](hubs/{r['id']}.md)"


def heading_slug(path, prefix):
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("## ") and line[3:].startswith(prefix):
            return sl.gh_slug(line[3:])
    raise SystemExit(f"build_role_map.py: no heading starting {prefix!r} in {path.name}")


def render(stack, scores, onto, archetypes):
    roles = scores["roles"]
    area_list = sl.areas(stack)
    layers = list(stack["layers"])
    by_home = OrderedDict((a, [r for r in roles if sl.home(r) == a]) for a in area_list)
    secondary = OrderedDict((a, [r for r in roles if a in r["stack"]["secondary"]]) for a in area_list)
    plane_touch = OrderedDict((a, [r for r in roles if a in r["stack"]["planes"] and sl.home(r) != a]) for a in stack["planes"])
    places = archetype_places(stack, onto, archetypes)
    tgt = sl.ROOT / "career" / "02-roles" / "genai-target-roles.md"
    rnk = sl.ROOT / "career" / "02-roles" / "role-rankings.md"
    bg_slug, lens_slug = heading_slug(tgt, "5. Best targets by background"), heading_slug(rnk, "5. Lenses")

    out = ["---", "id: roles.map", 'title: "The GenAI Role Map: Where the Work Sits"', "content_type: reference", "stage: 2",
           "status: published", f"last_verified: {stack['as_of']}",
           'summary: "Where each GenAI role\'s work sits: six stack layers from compute to applications, four cross-cutting planes, '
           'every role\'s footprint, the specialisations inside roles, and how to choose a direction. A map, not a pay model."',
           "sources: [T0-01, T0-03, T0-14, T1-03]", "generated_by: scripts/build_role_map.py", "---", "",
           "<!-- Generated by scripts/build_role_map.py from data/stack_model.json and data/role_scores.json. Edit the data, not this page. -->",
           "", "# The GenAI Role Map: Where the Work Sits", "",
           "> Six layers from compute to applications, four planes that cut across them, and where each of the "
           f"{len(roles)} canonical roles works. Use it to see the field at a glance, find roles near your strengths and spot adjacent moves.",
           "", "## How to read this map", "",
           "- **Layers** run from L1 (compute and hardware) up to L6 (applications and deployment). **Planes** cut across every layer: "
           "evaluation; security, safety and governance; product; leadership and independent practice.",
           "- Each role has a **work footprint**: the layer where most of its work sits, the other layers it regularly touches, and the planes it belongs to. "
           "Roles whose work is cross-cutting by nature have no main layer; their home is a plane.",
           "- Footprints are judgement (Grade D) drawn from each role's definition in the [role catalog](role-catalog.md). "
           "Titles are not layers: umbrella titles such as AI Engineer span several, which is why every role lists its other layers.",
           f"- **This is not a pay or demand model.** {stack['not_a_pay_model']}",
           "- To act on the map, open a role's hub (one page per role, with its evidence) or go to [choosing a direction](#choosing-a-direction).",
           "", "## The stack at a glance", "", "```mermaid", "flowchart TB"]
    order = sorted(layers, key=lambda k: -int(k[1:]))
    for code in order:
        out.append(f'  subgraph {code}["{sl.area_label(stack, code)}"]')
        out.append("    direction LR")
        members = by_home[code]
        if members:
            out += [f'    {code}_{r["id"].replace("-", "_")}["{r["name"]}"]' for r in members]
        else:
            out.append(f'    {code}_none["(no role is based here)"]')
        out.append("  end")
    out.append("  " + " ~~~ ".join(order))
    out.append('  subgraph planes["Cross-cutting planes"]')
    out.append("    direction LR")
    for code, p in stack["planes"].items():
        out.append(f'    subgraph p_{code}["{p["name"]}"]')
        out += [f'      p_{code}_{r["id"].replace("-", "_")}["{r["name"]}"]' for r in by_home[code]]
        out.append("    end")
    out += ["  end", "```", "",
            "Only each role's main place is drawn. The tables below add the other layers and planes it works in.", "",
            "## Layers", "",
            "| Layer | What happens here | Roles based here | Also work here | Skill categories | Proof-of-work archetypes placed here |",
            "|---|---|---|---|---|---|"]
    for code in order:
        a = stack["layers"][code]
        based = ", ".join(link(r) for r in by_home[code]) or "—"
        also = ", ".join(link(r) for r in secondary[code]) or "—"
        arch = "; ".join(f"{pid} {name}" for pid, name in places[code]) or "—"
        out.append(f"| **{code} {a['name']}** | {a['covers']} | {based} | {also} | {', '.join(a['categories'])} | {arch} |")
    out += ["", "Archetypes are placed where most of the skills they evidence sit (computed from the skill categories, Grade M). "
            "[Job-search strategy §2.6](../06-job-search/job-search-strategy.md#26-the-constraints-that-bind-first) computes which archetypes cover which roles.", "",
            "## Cross-cutting planes", "",
            "| Plane | What it covers | Roles based here | Roles that also work in it | Skill categories | Proof-of-work archetypes placed here |",
            "|---|---|---|---|---|---|"]
    for code, p in stack["planes"].items():
        based = ", ".join(link(r) for r in by_home[code]) or "—"
        also = ", ".join(link(r) for r in plane_touch[code]) or "—"
        arch = "; ".join(f"{pid} {name}" for pid, name in places[code]) or "—"
        out.append(f"| **{p['name']}** | {p['covers']} | {based} | {also} | {', '.join(p['categories']) or '—'} | {arch} |")
    out += ["", f"Cross-cutting skill categories that belong to no single layer: {', '.join(stack['cross_cutting_categories'])}.", "",
            "## Every role's footprint", "",
            "| Family | Role | Main place | Also works at | Planes | Basis (Grade D) |", "|---|---|---|---|---|---|"]
    families = OrderedDict()
    for r in roles:
        families.setdefault(r["family"], []).append(r)
    for fam, members in families.items():
        for r in members:
            st = r["stack"]
            main = sl.area_label(stack, st["primary"]) if st["primary"] else f"plane: {stack['planes'][st['planes'][0]]['name']}"
            also = ", ".join(sl.area_label(stack, x) for x in st["secondary"]) or "—"
            pl = ", ".join(stack["planes"][x]["name"] for x in st["planes"]) or "—"
            out.append(f"| {fam} | {link(r)} | {main} | {also} | {pl} | {st['basis']} |")
    out += ["", "## Specialisations inside canonical roles", "",
            "These are kinds of work that happen inside the canonical roles, not job titles. Many appear as titles in other guides; "
            "the catalog keeps them as aliases, candidates or quarantined titles until they pass its graduation tests "
            "([role catalog §1.4](role-catalog.md#14-quorum-and-graduation-tests-t0-01-d5), decision D-002). Recruiters still search for them, so they belong in your skills and project descriptions.", "",
            "| Specialisation | Where | Done inside | Key skills (ontology) | Status in the catalog |", "|---|---|---|---|---|"]
    ids = {r["id"]: r for r in roles}
    for s in stack["specialisations"]:
        where = sl.area_label(stack, s["where"])
        homes = ", ".join(link(ids[h]) for h in s["home"])
        skills = ", ".join(skill_name(onto, k) for k in s["skills"])
        out.append(f"| {s['name']} | {where} | {homes} | {skills} | {s['catalog']} |")
    out += ["", "## Choosing a direction", "",
            "The map shows where work sits; it does not tell you where to go. Two things do, and both rest on evidence:", "",
            f"1. **Your background.** The [GenAI target roles by background](genai-target-roles.md#{bg_slug}) and the "
            f"[persona lenses in the ranked catalog](role-rankings.md#{lens_slug}) score how reachable each role is from five starting points.",
            "2. **The interview track you can pass.** Employers interview by track, not by layer; pick the track whose loop you can prepare for:", "",
            "| Interview track | What it tests | Roles |", "|---|---|---|"]
    for tid, t in scores["interview_tracks"].items():
        members = ", ".join(link(r) for r in roles if r["interview_track"] == tid) or "—"
        out.append(f"| **{t['name']}** | {t['tests']} | {members} |")
    none = ", ".join(link(r) for r in roles if r["interview_track"] is None)
    out += ["", f"No interview-track evidence in the corpus: {none}. Sources: {next(iter(scores['interview_tracks'].values()))['source']}.", "",
            "Adjacent moves are cheapest where footprints overlap: a role's other layers are where its skills transfer. "
            "Each role hub lists the most similar roles by skill overlap, which is the measured version of the same idea.", "",
            "## Evidence and limits", "",
            f"- {stack['basis']}",
            "- The archetype placement is a model output (Grade M) computed from skill categories.",
            "- No layer has pay, demand or job-share figures, by design (decision D-015).",
            f"- Data as of {stack['as_of']} (stack model) and {scores['as_of']} (role scores).", "",
            "## Next steps", "",
            "- [Role hubs](hubs/README.md): one page per role with its numbers, skills, proof, interview track and résumé pointers.",
            "- [Role catalog](role-catalog.md) for definitions and evidence status; [GenAI target roles](genai-target-roles.md) for the target order.",
            "- [Role skill inventories](../03-skills-and-tech/role-skill-inventories.md) for every skill a role needs.",
            "- [Start Here](../README.md) for paths by situation and background.", ""]
    return "\n".join(out)


def build():
    stack, scores = sl.load(sl.STACK), sl.load(sl.SCORES)
    onto, archetypes = sl.load(sl.ONTOLOGY), sl.load(sl.ARCHETYPES)["archetypes"]
    errs = sl.errors(stack, scores, onto)
    if errs:
        raise SystemExit("stack model or role footprints are invalid:\n  " + "\n  ".join(errs))
    return render(stack, scores, onto, archetypes)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--update", action="store_true")
    g.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = build()
    if args.update:
        DOC.write_text(text, encoding="utf-8")
        print(f"wrote {DOC.relative_to(sl.ROOT)}")
    elif args.check:
        if not DOC.exists() or DOC.read_text(encoding="utf-8") != text:
            print(f"out of date: {DOC.relative_to(sl.ROOT)}")
            sys.exit(1)
        print("up to date")
    else:
        print(text)


if __name__ == "__main__":
    main()
