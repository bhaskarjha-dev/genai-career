def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--data", default=str(DATA))
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--check", action="store_true", help="exit 1 if any generated output is out of date")
    g.add_argument("--update", action="store_true", help="rewrite every generated output")
    g.add_argument("--stats", action="store_true", help="print coverage statistics")
    args = ap.parse_args()
    o = load_ontology(args.data)
    sessions = load_sessions()
    errs = validate_ontology(o, sessions)
    if errs:
        raise SystemExit("skills_ontology.json is invalid:\n  " + "\n  ".join(errs[:200]) +
                         (f"\n  ... and {len(errs) - 200} more" if len(errs) > 200 else ""))
    if args.stats:
        stats(o, sessions)
        return
    expected = outputs(o, sessions)
    if args.update:
        ROLE_DIR.mkdir(parents=True, exist_ok=True)
        stale_roles = [p for p in ROLE_DIR.glob("*.md") if p not in expected]
        for p in stale_roles:
            p.unlink()
        for path, text in expected.items():
            path.write_text(text, encoding="utf-8")
        print(f"updated {len(expected)} generated outputs" + (f"; removed {len(stale_roles)} stale role files" if stale_roles else ""))
        return
    stale = [str(p.relative_to(ROOT)) for p, text in expected.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    stale += [str(p.relative_to(ROOT)) + " (no longer generated)" for p in ROLE_DIR.glob("*.md") if p not in expected]
    if stale:
        print("out of date: " + ", ".join(stale))
        sys.exit(1)
    print(f"valid; {len(expected)} generated outputs up to date")


if __name__ == "__main__":
    main()
