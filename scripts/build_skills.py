def outputs(o, sessions):
    """Map every generated path to its expected full content."""
    counts = corpus_counts(o, sessions)
    res = OrderedDict()
    res[VOCAB_DOC] = apply_blocks(VOCAB_DOC.read_text(encoding="utf-8"), vocabulary_blocks(o, counts), VOCAB_BLOCKS)
    res[INDEX_DOC] = apply_blocks(INDEX_DOC.read_text(encoding="utf-8"), index_blocks(o), INDEX_BLOCKS)
    for rid, r in o["roles"].items():
        res[ROLE_DIR / f"{rid}.md"] = render_role(o, rid, r)
    res[ROLE_DIR / "README.md"] = render_inventory_readme(o)
    return res


def stats(o, sessions):
    counts = corpus_counts(o, sessions)
    anyt, mi, via = usage(o)
    S = o["skills"]
    concrete = [k for k, e in S.items() if e["type"] not in KNOWLEDGE and e["type"] not in NONTECH]
