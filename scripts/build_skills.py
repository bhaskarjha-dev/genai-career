#!/usr/bin/env python3
"""Skills ontology validator and generator for the GenAI career catalogs.

Reads data/skills_ontology.json, validates it against
data/schemas/skills_ontology.schema.json plus the referential and evidence rules
that JSON Schema cannot express, and generates:

  * career/03-skills-and-tech/skills-vocabulary.md        GENERATED blocks: summary, classes, vocabulary
                                       by type, credentials, watch list
  * career/03-skills-and-tech/role-skill-inventories.md   GENERATED blocks: role index, cross-role views,
                                       tier decisions, verification summary
  * career/03-skills-and-tech/inventories/<slug>.md  one fully generated file per role

Rules enforced beyond the schema:
  * every link, implements, parent, class member and credential ID resolves;
    implements and parent point to concepts or methods; no parent cycles
  * evidence: S links carry a grade and at least one real "T0-xx:L<line>" session
    reference; JD links carry a share and a "JobsPipe: <title>" source; S09 links
    carry a share and a "T0-03:L<line>" source
  * archived, dormant or retired tools and credentials are tiered X (Avoid)
  * every role covers all 19 types or records why a type does not apply, and
    has at least one Must, one communication and one behavioural link
  * individual-contributor target ranks run 1..N without gaps

Usage:
    python3 scripts/build_skills.py --check     # validate; exit 1 if any generated output is stale
    python3 scripts/build_skills.py --update    # validate; rewrite every generated output
    python3 scripts/build_skills.py --stats     # validate; print coverage statistics

Standard library only.
"""
