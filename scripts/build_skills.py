            if l["tier"] == tier:
                grade = {"JD": "B", "S09": "B", "S": l.get("grade", ""), "P": "D"}[l["ev"]]
                lines.append(f"| {esc(label(o, l['id'], l))} | {tier} | {l['ev']} ({grade}){' ' + l['share'] if l.get('share') else ''} | "
                             f"{esc(', '.join(l.get('src', []))) or '—'} | {esc(l.get('note', '')) or '—'} |")
