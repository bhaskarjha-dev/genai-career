def index_blocks(o):
    out = OrderedDict()
    rows = ["| Rank | Role | Variant | Skills | Must | Important | Should | Optional | Avoid | Evidenced (JD · S09 · S) | Practice-curated | Non-technical | Inventory |",
            "|:---:|---|:---:|:---:|:---:|:---:|:---:|:---:|:---:|:---:|:---:|:---:|---|"]
    for rid, r in sorted(o["roles"].items(), key=role_key):
        tiers, evs = role_stats(r)
        n = len(r["links"])
        nontech = sum(1 for l in r["links"] if link_type(o, l["id"]) in NONTECH)
        rows.append(f"| {rank_tag(r)} | {r['name']} | {r['flavour']} | {n} | {tiers['M']} | {tiers['I']} | {tiers['S']} | {tiers['O']} | {tiers['X']} | "
                    f"{evs['JD']} · {evs['S09']} · {evs['S']} | {evs['P']} ({round(100 * evs['P'] / n)}%) | {nontech} | [open](inventories/{rid}.md) |")
    out["index"] = "\n".join(rows)
    ic = [r for r in o["roles"].values() if r["variant"] != "L"]
    eng = [r for r in ic if r["variant"] in ("A", "B", "C", "D")]
    parts = []
    for title, pool, kinds in (
            (f"Concrete technologies most often at Must or Important across the {len(eng)} engineering and research roles", eng, "concrete"),
            (f"Knowledge skills (concepts and methods) most often at Must or Important across the {len(eng)} engineering and research roles", eng, "knowledge"),
            (f"Non-technical skills most often at Must or Important across all {len(ic)} individual-contributor roles", ic, "nontech")):
        mi, anyt = Counter(), Counter()
        for r in pool:
            for l in r["links"]:
                t = link_type(o, l["id"])
                kind = "knowledge" if t in KNOWLEDGE else "nontech" if t in NONTECH else "concrete"
                if kind != kinds:
                    continue
                if l["tier"] in ("M", "I"):
                    mi[l["id"]] += 1
                if l["tier"] != "X":
                    anyt[l["id"]] += 1
        top = sorted(anyt, key=lambda k: (-mi[k], -anyt[k], label(o, k).lower()))[:20]
        parts += [f"**{title}:**", "", "| Skill | Type | Must or Important in | Listed at any tier in |", "|---|---|:---:|:---:|"]
        for k in top:
            parts.append(f"| {esc(label(o, k))} | {o['meta']['types'][link_type(o, k)]['label']} | {mi[k]} ({round(100 * mi[k] / len(pool))}%) | "
                         f"{anyt[k]} ({round(100 * anyt[k] / len(pool))}%) |")
        parts.append("")
    out["universal"] = "\n".join(parts).rstrip("\n")
    changes = o.get("changes", [])
    rows = ["| Role | Skill | Tier | Why | Stage |", "|---|---|:---:|---|---|"]
    for ch in sorted(changes, key=lambda c: (role_key((c["role"], o["roles"][c["role"]])), c["stage"], c["id"])):
        name = label(o, ch["id"]) if (ch["id"] in o["skills"] or ch["id"] in o["classes"]) else ch["id"]
        rows.append(f"| {o['roles'][ch['role']]['name']} | {esc(name)} | {ch['to']} | {esc(ch['reason'])} | {ch['stage']} |")
    if not changes:
        rows.append("| — | — | — | No measured tier decisions recorded | — |")
    out["changes"] = "\n".join(rows)
    v = o["meta"].get("verification")
    if v:
        out["verification"] = "\n".join(f"- **{esc(k.replace('_', ' ').capitalize())}:** {esc(val)}" for k, val in v.items())
    else:
        out["verification"] = "- Not yet verified."
    return out


# ---------------------------------------------------------------- generated blocks in hand-written docs
def doc_blocks(text, labels):
    found = OrderedDict()
    for key, lab in labels.items():
        begin = f"<!-- BEGIN GENERATED: scripts/build_skills.py ({lab}) -->\n"
        if text.count(begin) != 1:
            raise SystemExit(f"expected exactly one marker {begin.strip()!r}")
        i = text.index(begin) + len(begin)
        j = text.find(END_MARKER, i - 1)
        if j < 0 or "<!-- BEGIN GENERATED" in text[i:j]:
            raise SystemExit(f"no END marker after {begin.strip()!r}")
        found[key] = (i, j)
    return found


def apply_blocks(text, blocks, labels):
    for key in reversed(list(labels)):
        i, j = doc_blocks(text, labels)[key]
        text = text[:i] + blocks[key] + text[j:]
    return text


