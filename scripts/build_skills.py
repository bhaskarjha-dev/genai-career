# ---------------------------------------------------------------- schema (a small JSON Schema subset, stdlib only)
def _is(value, kind):
    return {
        "object": isinstance(value, dict),
        "array": isinstance(value, list),
        "string": isinstance(value, str),
        "integer": isinstance(value, int) and not isinstance(value, bool),
        "number": isinstance(value, (int, float)) and not isinstance(value, bool),
        "boolean": isinstance(value, bool),
        "null": value is None,
    }[kind]


def schema_errors(inst, sch, root, path="$"):
    """Validate the subset of JSON Schema used by skills_ontology.schema.json."""
    if "$ref" in sch:
        node = root
        for part in sch["$ref"][2:].split("/"):
            node = node[part]
        return schema_errors(inst, node, root, path)
    errs = []
    if "const" in sch and inst != sch["const"]:
        errs.append(f"{path}: must equal {sch['const']!r}")
    if "enum" in sch and inst not in sch["enum"]:
        errs.append(f"{path}: {inst!r} is not one of {sch['enum']}")
    if "type" in sch:
        kinds = sch["type"] if isinstance(sch["type"], list) else [sch["type"]]
        if not any(_is(inst, k) for k in kinds):
            return errs + [f"{path}: expected {' or '.join(kinds)}"]
    if isinstance(inst, dict):
        errs += [f"{path}: missing \"{k}\"" for k in sch.get("required", []) if k not in inst]
        props, names, extra = sch.get("properties", {}), sch.get("propertyNames"), sch.get("additionalProperties", True)
        for k, v in inst.items():
            if names and not re.search(names["pattern"], k):
                errs.append(f"{path}: key {k!r} does not match {names['pattern']}")
            if k in props:
                errs += schema_errors(v, props[k], root, f"{path}.{k}")
            elif extra is False:
                errs.append(f"{path}: unexpected key \"{k}\"")
            elif isinstance(extra, dict):
                errs += schema_errors(v, extra, root, f"{path}.{k}")
    elif isinstance(inst, list):
        if len(inst) < sch.get("minItems", 0):
            errs.append(f"{path}: needs at least {sch['minItems']} items")
        if "items" in sch:
            for i, v in enumerate(inst):
                errs += schema_errors(v, sch["items"], root, f"{path}[{i}]")
    elif isinstance(inst, str):
        if len(inst) < sch.get("minLength", 0):
            errs.append(f"{path}: shorter than {sch['minLength']}")
        if "maxLength" in sch and len(inst) > sch["maxLength"]:
            errs.append(f"{path}: longer than {sch['maxLength']}")
        if "pattern" in sch and not re.search(sch["pattern"], inst):
            errs.append(f"{path}: {inst!r} does not match {sch['pattern']}")
    elif _is(inst, "number") and "minimum" in sch and inst < sch["minimum"]:
        errs.append(f"{path}: below {sch['minimum']}")
    return errs


# ---------------------------------------------------------------- referential and evidence rules
def link_type(o, lid):
    if lid in o["skills"]:
        return o["skills"][lid]["type"]
    if lid in o["classes"]:
        return o["skills"][o["classes"][lid]["members"][0]]["type"]
    return None


def integrity_errors(o, sessions):
    errs = []
    S, C, CR, R = o["skills"], o["classes"], o["credentials"], o["roles"]
    types, cats = o["meta"]["types"], set(o["meta"]["categories"])
    lines = {k: v.count("\n") + 1 for k, v in sessions.items()}
    for sid, e in S.items():
        if sid in C:
            errs.append(f"{sid}: used as both a skill and a class ID")
        if e["category"] not in cats:
            errs.append(f"skill {sid}: category {e['category']!r} is not in meta.categories")
        for k in e.get("implements", []) + ([e["parent"]] if "parent" in e else []):
            if k not in S or S[k]["type"] not in KNOWLEDGE:
                errs.append(f"skill {sid}: implements/parent {k!r} must be a concept or method")
        if e.get("match"):
            try:
                re.compile(e["match"])
            except re.error as ex:
                errs.append(f"skill {sid}: bad match regex ({ex})")
        seen, cur = {sid}, sid
        while "parent" in S.get(cur, {}):
            cur = S[cur]["parent"]
            if cur in seen:
                errs.append(f"skill {sid}: parent cycle")
                break
            seen.add(cur)
    for cid, c in C.items():
        missing = [m for m in c["members"] if m not in S]
        if missing:
            errs.append(f"class {cid}: unknown members {missing}")
        if len(set(c["members"])) != len(c["members"]):
            errs.append(f"class {cid}: duplicate members")
    flavours = {f for v in o["resume_variants"].values() for f in v["flavours"]}
    targets = []
    for rid, r in R.items():
        if r["variant"] not in o["resume_variants"] or r["flavour"] not in flavours or not r["flavour"].startswith(r["variant"]):
            errs.append(f"{rid}: inconsistent variant/flavour {r['variant']}/{r['flavour']}")
        if isinstance(r["target"], int):
            targets.append(r["target"])
        seen, covered = set(), Counter()
        for l in r["links"]:
            lid, where = l["id"], f"{rid} › {l['id']}"
            if lid in seen:
                errs.append(f"{where}: listed twice")
            seen.add(lid)
            t = link_type(o, lid)
            if t is None:
                errs.append(f"{where}: unknown skill or class")
                continue
            covered[t] += 1
            ev, src = l["ev"], l.get("src", [])
            if ev == "S":
                if "grade" not in l:
                    errs.append(f"{where}: S evidence needs a grade")
                refs = [m for m in (REF.match(s) for s in src) if m]
                if not refs:
                    errs.append(f"{where}: S evidence needs a session reference like T0-03:L512")
                for m in refs:
                    a, b = int(m.group(2)), int(m.group(3) or m.group(2))
                    if m.group(1) not in lines:
                        errs.append(f"{where}: unknown session {m.group(1)}")
                    elif not 1 <= a <= b <= lines[m.group(1)]:
                        errs.append(f"{where}: {m.group(0)} is outside {m.group(1)} (1..{lines[m.group(1)]})")
            else:
                if "grade" in l:
                    errs.append(f"{where}: grade applies to S evidence only")
                if ev == "JD" and ("share" not in l or not any("JobsPipe" in s for s in src)):
                    errs.append(f"{where}: JD evidence needs a share and a 'JobsPipe: <title>' source")
                if ev == "S09" and ("share" not in l or not any(s.startswith("T0-03:L") for s in src)):
                    errs.append(f"{where}: S09 evidence needs a share and a T0-03:L<line> source")
            if "n" in l and lid not in C:
                errs.append(f"{where}: 'n' applies to class links only")
            if S.get(lid, {}).get("status", {}).get("state") in DEAD and l["tier"] != "X":
                errs.append(f"{where}: {S[lid]['status']['state']} tool must be tiered X")
        for t in types:
            if not covered[t] and t not in r["none"]:
                errs.append(f"{rid}: type {t} has no links and no 'none' reason")
            if covered[t] and t in r["none"]:
                errs.append(f"{rid}: type {t} has links and a 'none' reason")
        errs += [f"{rid}: 'none' names unknown type {t}" for t in r["none"] if t not in types]
        errs += [f"{rid}: needs at least one {t} link" for t in ("communication", "behavioural") if not covered[t]]
        if not any(l["tier"] == "M" for l in r["links"]):
            errs.append(f"{rid}: needs at least one Must link")
        for cl in r["credentials"]:
            if cl["id"] not in CR:
                errs.append(f"{rid}: unknown credential {cl['id']}")
            elif CR[cl["id"]].get("status", {}).get("state") in DEAD and cl["tier"] != "X":
                errs.append(f"{rid}: retired credential {cl['id']} must be tiered X")
    if sorted(targets) != list(range(1, len(targets) + 1)):
        errs.append(f"IC target ranks must be 1..{len(targets)} without gaps: {sorted(targets)}")
    for ch in o.get("changes", []):
        if ch["role"] not in R or (ch["id"] not in S and ch["id"] not in C):
            errs.append(f"change {ch['role']}/{ch['id']}: unknown role or skill")
    return errs


def validate_ontology(o, sessions=None):
    """Return a list of problems (empty when valid)."""
    schema = json.loads(SCHEMA.read_text(encoding="utf-8"))
    errs = schema_errors(o, schema, schema)
    if errs:
        return errs  # referential checks assume a schema-valid document
    return integrity_errors(o, sessions if sessions is not None else load_sessions())


# ---------------------------------------------------------------- corpus mentions (concrete technologies only)
def patterns(e):
    if "match" in e:
        return [e["match"]] if e["match"] else []
    out = []
    for term in [e["name"].split(" (")[0]] + e.get("aliases", []):
        for part in term.split(" / "):
            part = part.strip()
            if len(part) >= 3 or (part == term and len(part) >= 2):
                out.append(r"(?<![A-Za-z0-9])" + re.escape(part) + r"(?![A-Za-z0-9])")
    return out


def corpus_counts(o, sessions):
    """Mentions per research session for every concrete skill; None means 'not counted' (ambiguous name)."""
    res = OrderedDict()
    for sid, e in o["skills"].items():
        if e["type"] in KNOWLEDGE or e["type"] in NONTECH:
            continue
        pats = patterns(e)
        if not pats:
            res[sid] = None
            continue
        rx = re.compile("|".join(f"(?:{p})" for p in pats))
        res[sid] = OrderedDict((k, n) for k, n in ((k, sum(1 for _ in rx.finditer(t))) for k, t in sessions.items()) if n)
    return res


# ---------------------------------------------------------------- shared rendering helpers
def short(name):
    return name.split(" (")[0]


def esc(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def sessions_of(link):
    out = []
    for s in link.get("src", []):
        m = REF.match(s)
        if m and m.group(1) not in out:
            out.append(m.group(1))
    return out


def tag(link):
    ev = link["ev"]
    if ev in ("JD", "S09"):
        return f"[{ev} {link['share']}]"
    if ev == "S":
        return f"[S · {', '.join(sessions_of(link))}]"
    return "[P]"


def label(o, lid, link=None):
    if lid in o["skills"]:
        return o["skills"][lid]["name"]
    c = o["classes"][lid]
    n = (link or {}).get("n", 1)
    return f"{short(c['name'])} (choose {n}: {' | '.join(short(o['skills'][m]['name']) for m in c['members'])})"


def usage(o):
    """For each skill/class ID: roles linking it at any non-X tier, roles linking it at M or I,
    and roles that cover it only through a choose-one class link."""
    anyt, mi, via = Counter(), Counter(), Counter()
    for r in o["roles"].values():
        direct = {l["id"] for l in r["links"]}
        covered = set()
        for l in r["links"]:
            if l["tier"] != "X":
                anyt[l["id"]] += 1
                if l["id"] in o["classes"]:
                    covered.update(m for m in o["classes"][l["id"]]["members"] if m not in direct)
            if l["tier"] in ("M", "I"):
                mi[l["id"]] += 1
        for m in covered:
            via[m] += 1
    return anyt, mi, via


def role_key(item):
    t = item[1]["target"]
    return (0, t) if isinstance(t, int) else (1, str(t))


def rank_tag(r):
    return f"#{r['target']}" if isinstance(r["target"], int) else r["target"]


def corpus_cell(counts):
    if counts is None:
        return "not counted (ambiguous name)"
    if not counts:
        return "0 (practice-curated)"
    top = sorted(counts.items(), key=lambda kv: -kv[1])
    return f"{sum(counts.values())} in {len(counts)}: " + ", ".join(f"{k} ×{n}" for k, n in top[:3]) + (" …" if len(top) > 3 else "")


# ---------------------------------------------------------------- vocabulary document
def vocabulary_blocks(o, counts):
    S, C, types = o["skills"], o["classes"], o["meta"]["types"]
    anyt, mi, via = usage(o)
    by_type = OrderedDict((t, [(k, e) for k, e in S.items() if e["type"] == t]) for t in types)
    out = OrderedDict()
    rows = ["| Group | Type | Entries | Named in the research corpus | Linked by at least one role | Where it goes on a resume |",
            "|---|---|:---:|:---:|:---:|---|"]
    for t, meta in types.items():
        items = by_type[t]
        if t in KNOWLEDGE or t in NONTECH:
            corpus = "n/a"
        else:
            corpus = str(sum(1 for k, _ in items if counts.get(k)))
        linked = sum(1 for k, _ in items if anyt[k] or mi[k] or via[k])
        rows.append(f"| {meta['group']} | [{meta['label']}](#type-{t.replace('_', '-')}) | {len(items)} | {corpus} | {linked} | {esc(meta['resume'])} |")
    concrete = [k for k, e in S.items() if e["type"] not in KNOWLEDGE and e["type"] not in NONTECH]
    rows.append(f"| **Total** | | **{len(S)}** | **{sum(1 for k in concrete if counts.get(k))} of {len(concrete)} concrete** | "
                f"**{sum(1 for k in S if anyt[k] or mi[k] or via[k])}** | |")
    out["summary"] = "\n".join(rows)
    rows = ["| Class | Members (any one satisfies a choose-1 link) | Note |", "|---|---|---|"]
    for cid, c in C.items():
        rows.append(f"| **{esc(short(c['name']))}** (`{cid}`) | {esc(', '.join(S[m]['name'] for m in c['members']))} | {esc(c.get('note', c.get('desc', '')))} |")
    out["classes"] = "\n".join(rows)
    parts = []
    for t, meta in types.items():
        items = by_type[t]
        parts.append(f'<a id="type-{t.replace("_", "-")}"></a>\n#### {meta["label"]} ({len(items)})\n')
        parts.append(f"*{meta['group']}. On a resume: {meta['resume']}.*\n")
        concrete_t = t not in KNOWLEDGE and t not in NONTECH
        head = "| Skill | Category | Posting wording (aliases) | Relations |" + (" Corpus mentions |" if concrete_t else "") + " Roles listing it |"
        parts.append(head)
        parts.append("|---|---|---|---|" + ("---|" if concrete_t else "") + ":---:|")
        for k, e in sorted(items, key=lambda kv: (kv[1]["category"], kv[1]["name"].lower())):
            name = f"**{esc(e['name'])}** (`{k}`)"
            st = e.get("status")
            if st:
                name += f" · *{st['state']} {st['as_of']}*"
            rel = []
            if e.get("parent"):
                rel.append("part of " + esc(S[e["parent"]]["name"]))
            if e.get("implements"):
                rel.append("→ " + esc(", ".join(short(S[x]["name"]) for x in e["implements"])))
            classes = [short(c["name"]) for c in C.values() if k in c["members"]]
            if classes:
                rel.append("in: " + esc(", ".join(classes)))
            row = f"| {name} | {esc(e['category'])} | {esc('; '.join(e.get('aliases', []))) or '—'} | {'; '.join(rel) or '—'} |"
            if concrete_t:
                row += f" {corpus_cell(counts.get(k))} |"
            cell = f"{anyt[k]} ({mi[k]} M/I)" if (anyt[k] or mi[k]) else ""
            if via[k]:
                cell += (" + " if cell else "") + f"{via[k]} via class"
            row += f" {cell or '—'} |"
            parts.append(row)
        parts.append("")
    out["vocabulary"] = "\n".join(parts).rstrip("\n")
    cred_roles = Counter()
    for r in o["roles"].values():
        for cl in r["credentials"]:
            cred_roles[cl["id"]] += 1
    rows = ["| Credential | Issuer | Level | Status | Roles that list it |", "|---|---|---|---|:---:|"]
    for cid, c in o["credentials"].items():
        st = c.get("status")
        stt = f"{st['state']} {st['as_of']}: {esc(st.get('note', ''))}" if st else "not in the research corpus (practice-curated)"
        rows.append(f"| **{esc(c['name'])}** (`{cid}`) | {esc(c['issuer'])} | {esc(c['level'])} | {stt} | {cred_roles[cid] or '—'} |")
    out["credentials"] = "\n".join(rows)
    rows = ["| Item | Type | Status | As of | What it means for a resume |", "|---|---|---|---|---|"]
    order = {"archived": 0, "dormant": 1, "retired": 2, "renamed": 3, "acquired": 4, "beta": 5, "development": 6, "active": 7}
    flagged = [(k, e) for k, e in S.items() if e.get("status")]
    for k, e in sorted(flagged, key=lambda kv: (order[kv[1]["status"]["state"]], kv[1]["name"].lower())):
        st = e["status"]
        rows.append(f"| **{esc(e['name'])}** | {types[e['type']]['label']} | {st['state']} | {st['as_of']} | {esc(st.get('note', ''))} |")
    out["watch"] = "\n".join(rows)
    return out


# ---------------------------------------------------------------- role inventories
def role_stats(r):
    tiers = Counter(l["tier"] for l in r["links"])
    evs = Counter(l["ev"] for l in r["links"])
    return tiers, evs


def typed_table(o, r):
    types = o["meta"]["types"]
    by_type = OrderedDict((t, []) for t in types)
    for l in r["links"]:
        by_type[link_type(o, l["id"])].append(l)
    rows = ["| Group | Type | Skills by tier, in priority order |", "|---|---|---|"]
    for t, links in by_type.items():
        if not links:
            continue
        cells = []
        for tier in TIERS:
            items = [f"{esc(label(o, l['id'], l))} {tag(l)}" for l in links if l["tier"] == tier]
            if items:
                cells.append(f"**{TIER_NAME[tier]}:** " + " · ".join(items))
        rows.append(f"| {types[t]['group']} | **{types[t]['label']}** | {'<br>'.join(cells)} |")
    return "\n".join(rows)


def keywords(o, r, limit=70):
    seen, out = set(), []
    for tier in ("M", "I", "S"):
        for l in r["links"]:
            if l["tier"] != tier:
                continue
            ids = o["classes"][l["id"]]["members"] if l["id"] in o["classes"] else [l["id"]]
            for sid in ids:
                e = o["skills"][sid]
                terms = [short(e["name"])] + e.get("aliases", [])[:2]
                for term in terms:
                    if term.lower() not in seen and len(term) > 1:
                        seen.add(term.lower())
                        out.append(term)
    return out[:limit]


