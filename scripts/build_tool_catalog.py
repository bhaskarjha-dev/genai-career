#!/usr/bin/env python3
"""Tool-catalog generator: builds career/00-start/tool-catalog.md from the evidence-graded tool data.

The charter asks the repository to evaluate the career-tool ecosystem "with an explicit rating rubric, evidence
grades and last-verified timestamps". Every tool in data/tools.json carries a verdict on a four-level rubric
(use, use with care, avoid, watch), the evidence behind it, its source line and the date it was checked. This
script groups them by lifecycle stage and sets the page's review_by date to 90 days after the oldest check
(EGP-1.0 expiry class for tool statuses).

Inputs (sources of truth):
  * data/tools.json (+ data/schemas/tools.schema.json)

Usage:
    python3 scripts/build_tool_catalog.py            # print the page
    python3 scripts/build_tool_catalog.py --update   # write career/00-start/tool-catalog.md
    python3 scripts/build_tool_catalog.py --check    # exit 1 if it is out of date or the data are invalid

Standard library only.
"""
import argparse
import datetime
import json
import re
import sys
from collections import OrderedDict
from pathlib import Path

sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_skills import schema_errors  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data" / "tools.json"
SCHEMA = ROOT / "data" / "schemas" / "tools.schema.json"
DOC = ROOT / "career" / "00-start" / "tool-catalog.md"
VERDICTS = OrderedDict([("use", "Use"), ("use-with-care", "Use with care"), ("avoid", "Avoid"), ("watch", "Watch")])
TTL_DAYS = 90


def esc(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def stage_folders():
    out = OrderedDict()
    for p in sorted((ROOT / "career").iterdir()):
        m = re.match(r"^(\d\d)-", p.name)
        if p.is_dir() and m:
            out[int(m.group(1))] = p.name
    return out


def stage_title(folder):
    path = ROOT / "career" / folder / "README.md"
    if path.exists():
        m = re.search(r"^# (.+)$", path.read_text(encoding="utf-8"), re.M)
        if m:
            return m.group(1)
    return folder


def validate(data):
    errs = []
    if SCHEMA.exists():
        schema = json.loads(SCHEMA.read_text(encoding="utf-8"))
        errs += [f"tools.json {e[2:]}" for e in schema_errors(data, schema, schema)]
        if errs:
            return errs
    seen, folders = set(), stage_folders()
    for t in data["tools"]:
        if t["id"] in seen:
            errs.append(f"tools.json: duplicate id {t['id']}")
        seen.add(t["id"])
        if t["verdict"] not in VERDICTS:
            errs.append(f"tools.json: {t['id']} verdict {t['verdict']!r} is not one of {list(VERDICTS)}")
        if t["stage"] not in folders:
            errs.append(f"tools.json: {t['id']} stage {t['stage']} has no folder under career/")
        try:
            datetime.date.fromisoformat(t["as_of"])
        except ValueError:
            errs.append(f"tools.json: {t['id']} as_of {t['as_of']!r} is not a date")
    return errs


def render(data):
    tools, rubric = data["tools"], data["rubric"]
    folders = stage_folders()
    oldest = min(datetime.date.fromisoformat(t["as_of"]) for t in tools)
    review_by = (oldest + datetime.timedelta(days=TTL_DAYS)).isoformat()
    by_stage = OrderedDict((s, [t for t in tools if t["stage"] == s]) for s in folders if any(t["stage"] == s for t in tools))
    count = lambda ts, v: sum(1 for t in ts if t["verdict"] == v)  # noqa: E731

    def link(stage):
        folder = folders[stage]
        target = "README.md" if folder == "00-start" else f"../{folder}/README.md"
        return f"[{stage_title(folder)}]({target})"

    sources = sorted({m for t in tools for m in re.findall(r"T[0-2]-\d\d", t["source"])})
    out = ["---", "id: start.tool-catalog", 'title: "Career Tool Catalog: What to Use, Use With Care, Avoid or Watch"',
           "content_type: reference", "stage: 0", "status: published", f"last_verified: {data['as_of']}", f"review_by: {review_by}",
           f'summary: "{len(tools)} external career tools and platforms across the lifecycle, each with a verdict (use, use with care, '
           'avoid, watch), the evidence behind it, its source and the date it was checked."',
           f"sources: [{', '.join(sources)}]", "tags: [tools, platforms, ecosystem]",
           "generated_by: scripts/build_tool_catalog.py", "---", "",
           "<!-- Generated by scripts/build_tool_catalog.py from data/tools.json. Edit the data, not this page. -->", "",
           "# Career Tool Catalog: What to Use, Use With Care, Avoid or Watch", "",
           f"> {len(tools)} external tools and platforms across the career lifecycle, each with a verdict, the evidence behind it and "
           "the date it was checked.", "",
           "## How to read the verdicts", "",
           "| Verdict | Meaning | Tools |", "|---|---|:---:|"]
    out += [f"| **{label}** | {esc(rubric.get(v, ''))} | {count(tools, v)} |" for v, label in VERDICTS.items()]
    out += ["", f"- **Evidence grades** follow EGP-1.0: A primary, B transparent secondary, C vendor or single source, D judgement.",
            f"- **Dates:** each tool shows when it was checked. Tool facts expire after {TTL_DAYS} days; this page is due for "
            f"re-verification by {review_by}.",
            "- **No endorsement.** A verdict describes what the research found about a tool's fitness for a job-search task. "
            "It is not a recommendation to buy, and it does not rank vendors that were not assessed.", "",
            "## At a glance", "",
            "| Stage | " + " | ".join(VERDICTS.values()) + " |", "|---|" + ":---:|" * len(VERDICTS)]
    for s, ts in by_stage.items():
        out.append(f"| {link(s)} | " + " | ".join(str(count(ts, v)) for v in VERDICTS) + " |")
    out += ["", "## Tools by stage", ""]
    for s, ts in by_stage.items():
        out += [f"### {stage_title(folders[s])}", "",
                "| Tool | Category | What it is | Verdict | Why | Evidence | As of |", "|---|---|---|---|---|:---:|---|"]
        order = {v: i for i, v in enumerate(VERDICTS)}
        for t in sorted(ts, key=lambda t: (order[t["verdict"]], t["name"].lower())):
            name = f"[{esc(t['name'])}]({t['url']})" if t.get("url") else esc(t["name"])
            status = f" ({esc(t['status'])})" if t.get("status") else ""
            out.append(f"| **{name}**{status} | {esc(t['category'])} | {esc(t['what'])} | {VERDICTS[t['verdict']]} | {esc(t['why'])} | "
                       f"{t['evidence']} · {esc(t['source'])} | {t['as_of']} |")
        out.append("")
    avoid = [t for t in tools if t["verdict"] == "avoid"]
    if avoid:
        out += ["## The avoid list", "", "Tools and practices the research found harmful or unreliable for a job search:", ""]
        out += [f"- **{esc(t['name'])}** ({stage_title(folders[t['stage']])}): {t['why']} [{t['evidence']} · {t['source']}]" for t in avoid]
        out.append("")
    out += ["## Evidence and limits", "",
            f"- {data['basis']}",
            "- Communities are not tools: they are rated in the [communities guide](../07-networking/communities-guide.md).",
            f"- Data as of {data['as_of']}; the oldest check is {oldest.isoformat()}.", "",
            "## Next steps", "",
            "- [Channels and boards](../06-job-search/channels-and-boards.md): where postings are and which channels convert.",
            "- [ATS mechanics](../06-job-search/ats-mechanics.md): why \"ATS score\" checkers and auto-apply tools get the verdicts they do.",
            "- [Application operating system](../06-job-search/application-operating-system.md): the tracker and weekly rhythm.",
            "- [Start Here](../README.md)", ""]
    return "\n".join(out)


def build():
    data = json.loads(DATA.read_text(encoding="utf-8"), object_pairs_hook=OrderedDict)
    errs = validate(data)
    if errs:
        raise SystemExit("tools data are invalid:\n  " + "\n  ".join(errs[:30]))
    return render(data)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--update", action="store_true")
    g.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = build()
    if args.update:
        DOC.write_text(text, encoding="utf-8")
        print(f"wrote {DOC.relative_to(ROOT)}")
    elif args.check:
        if not DOC.exists() or DOC.read_text(encoding="utf-8") != text:
            print(f"out of date: {DOC.relative_to(ROOT)}")
            sys.exit(1)
        print("up to date")
    else:
        print(text)


if __name__ == "__main__":
    main()
